const MIN_NODE = [22, 5]

function nodeOk() {
  const [major, minor] = process.versions.node.split(".").map(Number)
  return major > MIN_NODE[0] || (major === MIN_NODE[0] && minor >= MIN_NODE[1])
}

if (!nodeOk()) {
  console.error(`error: Node >= ${MIN_NODE.join(".")} is required (found ${process.versions.node}).`)
  console.error("The email agent uses the built-in node:sqlite module.")
  process.exit(1)
}

function parseArgs(args) {
  const flags = {}
  const positional = []
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index]
    if (!arg.startsWith("--")) {
      positional.push(arg)
      continue
    }
    const body = arg.slice(2)
    const eq = body.indexOf("=")
    if (eq !== -1) {
      flags[body.slice(0, eq)] = body.slice(eq + 1)
      continue
    }
    const next = args[index + 1]
    if (next && !next.startsWith("--")) {
      flags[body] = next
      index += 1
    } else {
      flags[body] = true
    }
  }
  return { flags, positional }
}

function fail(message) {
  console.error(`error: ${message}`)
  process.exit(1)
}

function readStdin() {
  try {
    return readFileSync(0, "utf8")
  } catch {
    return ""
  }
}

function withService(fn, file) {
  const instance = createService(openStore(file))
  return Promise.resolve(fn(instance)).finally(() => {
    closeTransports()
    instance.store.close()
  })
}

