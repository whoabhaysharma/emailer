/* ----------------------------------- main ---------------------------------- */

const { flags, positional } = parseArgs(process.argv.slice(2))
const command = positional.shift()

try {
  switch (command) {
    case "init":
      await cmdInit(flags)
      break
    case "setup":
      await cmdSetup(flags)
      break
    case "account": {
      const action = positional.shift()
      if (!action || action === "list") printAccounts(flags)
      else if (action === "add") await cmdAccountAdd(flags)
      else if (action === "test") await cmdAccountTest(flags, positional)
      else if (action === "warmup") await cmdAccountWarmup(flags, positional)
      else if (action === "remove") {
        const id = positional[0]
        if (!id) fail("account id is required")
        saveAccounts(loadAccounts().filter((account) => account.id !== id))
        console.log(`removed ${id}`)
      } else fail(`unknown account action: ${action}`)
      break
    }
    case "secret": {
      const action = positional.shift()
      if (action !== "set") fail("usage: secret set <accountId>")
      const id = positional[0]
      if (!id) fail("account id is required")
      const account = getAccount(id)
      const value = flags.password || (await promptHidden(`Google app password for ${account.email} (hidden): `))
      if (!value) fail("empty password")
      setSecret(account, value, { useKeychain: !flags["no-keychain"] })
      saveAccounts(loadAccounts().map((entry) => (entry.id === account.id ? { ...entry, secretRef: account.secretRef } : entry)))
      console.log(`stored secret for ${id}`)
      break
    }
    case "doctor":
      await cmdDoctor()
      break
    case "inbox":
      await cmdInbox(flags)
      break
    case "stats":
      await cmdStats(flags)
      break
    case "search":
      await cmdSearch(flags)
      break
    case "thread":
      await cmdThread(positional)
      break
    case "send":
      await cmdSend(flags)
      break
    case "draft":
      await cmdDraft(flags)
      break
    case "contacts":
      await cmdContacts(positional.shift(), flags, positional)
      break
    case "campaign":
      await cmdCampaign(positional.shift(), flags, positional)
      break
    case "pause-all":
      await withService(async (instance) => printJson(instance.pauseAll()))
      break
    case "resume-all":
      await withService(async (instance) => printJson(instance.resumeAll()))
      break
    case "sync":
      await withService(async (instance) => printJson(await instance.syncAll()))
      break
    case "daemon":
      await cmdDaemon(flags)
      break
    case "service":
      cmdService(positional[0] || "status")
      break
    case "config":
      cmdConfig(positional[0] || "show", positional.slice(1), flags)
      break
    case "status": {
      const status = daemonStatus()
      const health = await withService(async (instance) => instance.health()).catch(() => null)
      printJson({ ...status, health, token: existsSync(tokenFile), pidFile })
      break
    }
    case "version":
    case "--version":
      console.log(VERSION)
      break
    case undefined:
    case "help":
    case "--help":
      printHelp()
      break
    default:
      fail(`unknown command: ${command}. Run --help.`)
  }
} catch (error) {
  fail(String(error?.message || error))
}
