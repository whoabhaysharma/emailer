/* ---------------------------------- config --------------------------------- */

function setPath(object, path, value) {
  const keys = String(path).split(".")
  let cursor = object
  for (const key of keys.slice(0, -1)) {
    if (typeof cursor[key] !== "object" || cursor[key] === null) cursor[key] = {}
    cursor = cursor[key]
  }
  cursor[keys[keys.length - 1]] = value
}

function getPath(object, path) {
  return String(path)
    .split(".")
    .reduce((cursor, key) => (cursor && typeof cursor === "object" ? cursor[key] : undefined), object)
}

function cmdConfig(action, positional, flags) {
  if (!action || action === "show") return printJson(loadConfig())
  if (action === "path") return console.log(configFile)
  if (action === "edit") {
    const editor = process.env.VISUAL || process.env.EDITOR || "vi"
    const result = spawnSync(editor, [configFile], { stdio: "inherit" })
    if (result.status !== 0) fail(`editor exited with ${result.status}`)
    return
  }
  if (action === "set") {
    const pairs = positional.length ? positional : Object.entries(flags).map(([key, value]) => `${key}=${value}`)
    if (!pairs.length) fail("usage: config set key=value [key=value...]")
    const cfg = loadConfig()
    for (const pair of pairs) {
      const eq = String(pair).indexOf("=")
      if (eq === -1) fail(`expected key=value, got "${pair}"`)
      const key = pair.slice(0, eq)
      const raw = pair.slice(eq + 1)
      const current = getPath(cfg, key)
      let value = raw
      if (typeof current === "boolean") value = raw === "true" || raw === "1"
      else if (typeof current === "number" && raw.trim() !== "" && !Number.isNaN(Number(raw))) value = Number(raw)
      else if (raw === "true") value = true
      else if (raw === "false") value = false
      setPath(cfg, key, value)
    }
    return printJson(saveConfig(cfg))
  }
  fail(`unknown config action: ${action}. Use show, set, edit, path.`)
}

/* ---------------------------------- daemon --------------------------------- */

async function cmdDaemon(flags) {
  const result = await startDaemon({ port: flags.port, once: flags.once === true, quiet: flags.quiet === true })
  if (!result) return
  if (flags.once !== true) {
    console.log(`daemon running at ${result.address}`)
    await new Promise(() => {})
  }
}

function cmdService(action) {
  const platform = process.platform
  const node = process.execPath
  const cli = join(packageRoot, "src", "cli.js")

  if (platform === "darwin") {
    const label = "dev.opencode.email-agent"
    const plist = join(homedir(), "Library", "LaunchAgents", `${label}.plist`)
    if (action === "install") {
      mkdirSync(dirname(plist), { recursive: true })
      mkdirSync(dirname(logFile), { recursive: true })
      stopDaemon()
      writeFileSync(
        plist,
        `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${label}</string>
  <key>ProgramArguments</key>
  <array>
    <string>${node}</string>
    <string>${cli}</string>
    <string>daemon</string>
    <string>--quiet</string>
  </array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>${logFile}</string>
  <key>StandardErrorPath</key><string>${logFile}</string>
  <key>EnvironmentVariables</key>
  <dict><key>PATH</key><string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin</string></dict>
</dict>
</plist>
`,
      )
      try {
        execFileSync("launchctl", ["unload", plist], { stdio: "ignore" })
      } catch {}
      execFileSync("launchctl", ["load", plist], { stdio: "inherit" })
      console.log(`installed launch agent: ${plist}`)
      return
    }
    if (action === "uninstall") {
      try {
        execFileSync("launchctl", ["unload", plist], { stdio: "ignore" })
      } catch {}
      stopDaemon()
      try {
        execFileSync("rm", ["-f", plist])
      } catch {}
      console.log("removed launch agent")
      return
    }
    console.log(daemonStatus().running ? `running (pid ${daemonStatus().pid})` : "not running")
    console.log(`plist: ${plist}`)
    return
  }

  if (platform === "linux") {
    const unitDir = join(homedir(), ".config", "systemd", "user")
    const unit = join(unitDir, "opencode-email-agent.service")
    if (action === "install") {
      mkdirSync(unitDir, { recursive: true })
      writeFileSync(
        unit,
        `[Unit]
Description=OpenCode email agent
After=network-online.target

[Service]
ExecStart=${node} ${cli} daemon --quiet
Restart=always
RestartSec=5
Environment=PATH=/usr/local/bin:/usr/bin:/bin

[Install]
WantedBy=default.target
`,
      )
      execFileSync("systemctl", ["--user", "daemon-reload"], { stdio: "inherit" })
      execFileSync("systemctl", ["--user", "enable", "--now", "opencode-email-agent"], { stdio: "inherit" })
      console.log(`installed systemd unit: ${unit}`)
      return
    }
    if (action === "uninstall") {
      try {
        execFileSync("systemctl", ["--user", "disable", "--now", "opencode-email-agent"], { stdio: "inherit" })
      } catch {}
      try {
        execFileSync("rm", ["-f", unit])
      } catch {}
      console.log("removed systemd unit")
      return
    }
    console.log(daemonStatus().running ? `running (pid ${daemonStatus().pid})` : "not running")
    return
  }

  console.log("service install is supported on macOS (launchd) and Linux (systemd). Use: opencode-email-agent daemon")
}

