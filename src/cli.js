function parseCsvLine(line) {
  const values = []
  let current = ""
  let quoted = false
  for (let index = 0; index < line.length; index += 1) {
    const char = line[index]
    if (quoted) {
      if (char === '"' && line[index + 1] === '"') {
        current += '"'
        index += 1
      } else if (char === '"') {
        quoted = false
      } else {
        current += char
      }
    } else if (char === '"') {
      quoted = true
    } else if (char === ",") {
      values.push(current.trim())
      current = ""
    } else {
      current += char
    }
  }
  values.push(current.trim())
  return values
}

function parseContactsFile(file) {
  const raw = readFileSync(file, "utf8").trim()
  if (!raw) return []
  if (raw.startsWith("[") || raw.startsWith("{")) {
    const parsed = JSON.parse(raw)
    return Array.isArray(parsed) ? parsed : parsed.contacts || []
  }
  const lines = raw.split(/\r?\n/).filter(Boolean)
  const header = parseCsvLine(lines[0]).map((value) => value.trim().toLowerCase())
  return lines.slice(1).map((line) => {
    const values = parseCsvLine(line)
    const entry = {}
    header.forEach((key, index) => {
      entry[key] = values[index]
    })
    return { email: entry.email || entry["e-mail"], name: entry.name, company: entry.company, title: entry.title }
  })
}

async function cmdContacts(action, flags, positional) {
  await withService(async (instance) => {
    if (!action || action === "list") {
      const contacts = instance.listContacts({ query: flags.query, status: flags.status, limit: flags.limit || 100 })
      if (flags.json) return printJson(contacts)
      console.table(
        contacts.map((contact) => ({
          email: contact.email,
          name: contact.name || "",
          company: contact.company || "",
          status: contact.status,
          consent: contact.consent_at ? "yes" : "",
          notBefore: contact.not_before ? String(contact.not_before).slice(0, 10) : "",
          lastContact: String(contact.last_contacted_at || "").slice(0, 10),
        })),
      )
      return
    }

    if (action === "import") {
      if (!flags.file) fail("--file contacts.csv|contacts.json is required")
      const contacts = parseContactsFile(flags.file)
      if (!contacts.length) fail("no contacts found in file")
      const result = instance.importContacts({ contacts, source: flags.source || "import", consented: flags.consented === true })
      printJson(result)
      return
    }

    if (action === "show") {
      const email = positional[0]
      if (!email) fail("email is required")
      const contact = instance.getContact(email)
      if (!contact) fail(`contact not found: ${email}`)
      printJson({ contact, messages: instance.searchMessages({ from: email, limit: 25 }) })
      return
    }

    if (action === "status") {
      const email = positional[0]
      const status = positional[1]
      if (!email || !status) fail("usage: contacts status <email> <status>")
      printJson(instance.setContactStatus(email, status, flags["not-before"]))
      return
    }

    fail(`unknown contacts action: ${action}`)
  })
}

/* --------------------------------- campaigns -------------------------------- */

async function cmdCampaign(action, flags, positional) {
  await withService(async (instance) => {
    if (action === "list" || !action) {
      const campaigns = instance.listCampaigns()
      if (flags.json) return printJson(campaigns)
      if (!campaigns.length) return console.log("no campaigns yet")
      console.table(
        campaigns.map((campaign) => ({
          id: campaign.id.slice(0, 8),
          name: campaign.name,
          mode: campaign.mode,
          status: campaign.status,
          steps: campaign.steps.length,
          active: campaign.stats.active || 0,
          replied: campaign.stats.replied || 0,
          done: campaign.stats.done || 0,
        })),
      )
      return
    }

    if (action === "create") {
      if (!flags.file) fail("--file campaign.json is required")
      printJson(instance.createCampaign(JSON.parse(readFileSync(flags.file, "utf8"))))
      return
    }

    if (action === "pause-all") return printJson(instance.pauseAll())
    if (action === "resume-all") return printJson(instance.resumeAll())
    if (action === "tick") return printJson(await instance.tickCampaigns())

    const id = positional[0] || flags.id
    if (!id) fail("campaign id is required")

    if (action === "show") return printJson(instance.getCampaign(id))
    if (action === "preview") {
      return printJson(await instance.previewCampaign(id, { to: flags.to, contactEmail: flags.contact, dryRun: flags["dry-run"] === true }))
    }
    if (["start", "pause", "resume", "done"].includes(action)) {
      const status = action === "start" || action === "resume" ? "running" : action === "pause" ? "paused" : "done"
      return printJson(instance.setCampaignStatus(id, status))
    }
    if (action === "enrol") {
      let contacts = []
      if (flags.file) contacts = parseContactsFile(flags.file)
      else if (flags.emails) contacts = String(flags.emails).split(/[\s,;]+/).filter(Boolean).map((email) => ({ email }))
      if (!contacts.length) fail("provide --emails or --file")
      return printJson(instance.enrolContacts({ campaignId: id, contacts }))
    }

    fail(`unknown campaign action: ${action}`)
  })
}

